"""Regenerate src/unicode.rs: ranges of Unicode punctuation (categories P* and S*, as CommonMark
0.31 defines "Unicode punctuation") and Unicode whitespace (Zs plus tab, LF, FF, CR)."""

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(f, name, rs):
    f.write(f"pub(crate) static {name}: &[(u32, u32)] = &[\n")
    for a, b in rs:
        f.write(f"    (0x{a:X}, 0x{b:X}),\n")
    f.write("];\n\n")


def main() -> None:
    punct = ranges(lambda c: unicodedata.category(c)[0] in "PS")
    space = ranges(lambda c: unicodedata.category(c) == "Zs" or c in "\t\n\x0c\r")
    with open("src/unicode.rs", "w") as f:
        f.write(f"// Generated by scripts/gen_unicode.py from Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]}).\n\n")
        emit(f, "PUNCTUATION", punct)
        emit(f, "WHITESPACE", space)
        f.write("fn in_ranges(table: &[(u32, u32)], c: char) -> bool {\n")
        f.write("    let c = c as u32;\n    table.binary_search_by(|&(a, b)| if c < a { std::cmp::Ordering::Greater } else if c > b { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_ok()\n}\n\n")
        f.write("/// Unicode punctuation as CommonMark 0.31 defines it (general categories P and S).\n")
        f.write("pub(crate) fn is_punctuation(c: char) -> bool {\n    if c.is_ascii() { c.is_ascii_punctuation() } else { in_ranges(PUNCTUATION, c) }\n}\n\n")
        f.write("/// Unicode whitespace: category Zs, tab, line feed, form feed, carriage return.\n")
        f.write("pub(crate) fn is_whitespace(c: char) -> bool {\n    in_ranges(WHITESPACE, c)\n}\n")


if __name__ == "__main__":
    main()
